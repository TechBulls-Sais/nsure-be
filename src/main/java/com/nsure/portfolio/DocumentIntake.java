package com.nsure.portfolio;

import java.util.Set;

/**
 * How a document came to be on record, and the labels the register and document lists show for it (SH09A records:
 * source, scan state and classification). A file is called clean only when a configured scanner said so.
 */
public final class DocumentIntake {

    /** Made by Nsure itself (schedules, claim summaries): not an upload, so there is nothing to scan. */
    public static final String GENERATED = "GENERATED";
    /** An upload a configured scanner passed. */
    public static final String CLEAN = "CLEAN";
    /** An upload a person released from quarantine without a malware scan, because no scanner is configured. */
    public static final String RELEASED_UNSCANNED = "RELEASED_UNSCANNED";
    /** An upload stored before uploads were quarantined; it was never scanned. */
    public static final String NOT_SCANNED = "NOT_SCANNED";
    /** An upload still in quarantine (QUARANTINED in document lists). */
    public static final String QUARANTINED = "QUARANTINED";
    /** An upload that was not accepted (a person's decision, or a scanner finding). */
    public static final String REJECTED = "REJECTED";

    public static final String SYSTEM = "SYSTEM";
    public static final String STAFF = DocumentCustody.STAFF;
    public static final String PORTAL = DocumentCustody.PORTAL;
    /** An upload stored before its channel was recorded. */
    public static final String UPLOAD = "UPLOAD";

    private static final Set<String> HEALTH = Set.of("Medical report", "Hospital bill", "Death certificate");

    private DocumentIntake() {
    }

    public static String scanLabel(String scanStatus) {
        return switch (scanStatus == null ? "" : scanStatus) {
            case GENERATED -> "Generated by Nsure (not an upload)";
            case CLEAN -> "Scanned: no threat found";
            case RELEASED_UNSCANNED -> "Not scanned: released by a person";
            case NOT_SCANNED -> "Not scanned: stored before uploads were quarantined";
            case QUARANTINED -> "In quarantine: not scanned, waiting for release";
            case REJECTED -> "Rejected";
            default -> "Unknown";
        };
    }

    public static String sourceLabel(String channel) {
        return switch (channel == null ? "" : channel) {
            case SYSTEM -> "Generated by Nsure";
            case STAFF -> "Uploaded by staff";
            case PORTAL -> "Uploaded in the customer portal";
            default -> "Uploaded";
        };
    }

    /**
     * The handling class of a document type. Health evidence and identity documents are special-category or personal
     * data and are labelled as such; everything else on a policy or claim is confidential.
     */
    public static String classification(String documentType) {
        if (documentType != null && HEALTH.contains(documentType)) {
            return "Sensitive: health";
        }
        if ("Identity document".equals(documentType)) {
            return "Sensitive: identity";
        }
        return "Confidential";
    }
}
