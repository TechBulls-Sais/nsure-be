package com.nsure.portfolio;

import com.nsure.common.exception.NotFoundException;
import com.nsure.security.domain.AppUser;
import com.nsure.security.exception.NoAuthorizationException;
import com.nsure.security.service.PlatformSecurityContext;
import jakarta.persistence.EntityManager;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.multipart.MultipartFile;

/**
 * Claim evidence files: PDF, JPG or PNG up to 10 MB, stored on local disk by {@link DocumentFiles}.
 * Staff need a claim permission; a customer may only touch claims on their own policies.
 */
@Service
public class ClaimDocumentService {

    public static final long MAX_BYTES = 10L * 1024 * 1024;

    public static final List<String> TYPES = List.of(
            "Identity document", "Signed declaration", "Death certificate", "Medical report", "Hospital bill",
            "Supporting evidence");

    private static final String DEFAULT_TYPE = "Supporting evidence";
    /** Generated by the system, never uploaded, so it is not in TYPES. */
    public static final String SUMMARY_TYPE = "Claim summary";
    private static final DateTimeFormatter FILE_STAMP = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss");
    private static final Set<String> CLOSED = Set.of(ClaimWorkflow.PAID, ClaimWorkflow.REJECTED);

    /** Who may upload on the staff side: anyone who can lodge, update or assess a claim. */
    private static final List<String> STAFF_UPLOAD = List.of("UPDATE_CLAIM", "CREATE_CLAIM", "ASSESS_CLAIM");

    private final EntityManager em;
    private final ClaimWorkflow claims;
    private final WorkflowHistory history;
    private final PlatformSecurityContext security;
    private final PortfolioService portfolio;
    private final DocumentFiles files;

    public ClaimDocumentService(EntityManager em, ClaimWorkflow claims, WorkflowHistory history,
            PlatformSecurityContext security, PortfolioService portfolio, DocumentFiles files) {
        this.em = em;
        this.claims = claims;
        this.history = history;
        this.security = security;
        this.portfolio = portfolio;
        this.files = files;
    }

    /** A document's bytes plus what the download response needs to describe them. */
    public record StoredFile(String fileName, String contentType, long size, Resource resource) {
    }

    // ── staff ────────────────────────────────────────────────────────────────────────────────────────

    @Transactional(readOnly = true)
    public List<PortfolioViews.DocumentView> list(String ref) {
        security.authenticatedUser().validateHasPermissionTo("READ_CLAIM");
        return views(em, claims.claim(ref).getId());
    }

    @Transactional
    public List<PortfolioViews.DocumentView> upload(String ref, MultipartFile file, String type) {
        AppUser staff = security.authenticatedUser();
        if (STAFF_UPLOAD.stream().noneMatch(staff::hasPermissionTo)) {
            throw new NoAuthorizationException("User has no authority to add documents to a claim");
        }
        InsuranceClaim claim = claims.claim(ref);
        store(claim, file, type, staff.getUsername());
        return views(em, claim.getId());
    }

    @Transactional(readOnly = true)
    public StoredFile download(String ref, Long id) {
        security.authenticatedUser().validateHasPermissionTo("READ_CLAIM");
        return open(claims.claim(ref), id);
    }

    /**
     * Builds a claim summary PDF from the claim as it stands now and files it with the claim's documents. Each
     * call adds a new dated snapshot, so it also works on Paid and Rejected claims.
     */
    @Transactional
    public List<PortfolioViews.DocumentView> generateSummary(String ref) {
        AppUser staff = security.authenticatedUser();
        if (STAFF_UPLOAD.stream().noneMatch(staff::hasPermissionTo)) {
            throw new NoAuthorizationException("User has no authority to generate claim documents");
        }
        InsuranceClaim claim = claims.claim(ref);
        byte[] pdf = ClaimSummaryPdf.render(claim, ClaimWorkflow.results(claim), views(em, claim.getId()),
                history.of(WorkflowHistory.CLAIM, ref), staff.getUsername());
        String fileName = claim.getRef() + "-summary-" + LocalDateTime.now().format(FILE_STAMP) + ".pdf";
        save(claim, pdf, fileName, "pdf", "application/pdf", SUMMARY_TYPE, staff.getUsername(), "Summary Generated");
        return views(em, claim.getId());
    }

    // ── customer portal ──────────────────────────────────────────────────────────────────────────────

    @Transactional
    public PortfolioViews.ShopView shopUpload(String ref, MultipartFile file, String type) {
        CustomerAccount account = portfolio.customerForLogin();
        store(ownClaim(account, ref), file, type, account.getLoginUsername());
        return portfolio.shop();
    }

    @Transactional(readOnly = true)
    public StoredFile shopDownload(String ref, Long id) {
        return open(ownClaim(portfolio.customerForLogin(), ref), id);
    }

    /** The documents on one claim, oldest first. */
    static List<PortfolioViews.DocumentView> views(EntityManager em, Long claimId) {
        return em.createQuery("select d from ClaimDocument d where d.claimId = :claim order by d.id", ClaimDocument.class)
                .setParameter("claim", claimId)
                .getResultStream()
                .map(d -> new PortfolioViews.DocumentView(
                        d.getId(), d.getDocumentType(), d.getFileName(), d.getContentType(), d.getSizeBytes(),
                        d.getUploadedBy(), d.getUploadedAt().withNano(0).toString()))
                .toList();
    }

    private InsuranceClaim ownClaim(CustomerAccount account, String ref) {
        InsuranceClaim claim = claims.claim(ref);
        if (!claim.getCustomerName().equals(account.getName())) {
            // Not theirs: answer as if it did not exist rather than confirm someone else's claim number.
            throw new NotFoundException("Claim " + ref + " not found");
        }
        return claim;
    }

    private void store(InsuranceClaim claim, MultipartFile file, String type, String uploadedBy) {
        if (CLOSED.contains(claim.getStatus())) {
            throw new IllegalArgumentException("Documents can only be added while the claim is open.");
        }
        String documentType = type == null || type.isBlank() ? DEFAULT_TYPE : type.trim();
        if (!TYPES.contains(documentType)) {
            throw new IllegalArgumentException("Document type must be one of: " + String.join(", ", TYPES) + ".");
        }
        if (file == null || file.isEmpty()) {
            throw new IllegalArgumentException("Choose a file to upload.");
        }
        if (file.getSize() > MAX_BYTES) {
            throw new IllegalArgumentException("Files can be at most 10 MB.");
        }
        byte[] bytes;
        try {
            bytes = file.getBytes();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        String fileName = cleanName(file.getOriginalFilename());
        String extension = extension(fileName);
        String contentType = detect(bytes);
        if (contentType == null || !matches(contentType, extension)) {
            throw new IllegalArgumentException("Only PDF, JPG and PNG files can be uploaded.");
        }
        save(claim, bytes, fileName, extension.equals("jpeg") ? "jpg" : extension, contentType, documentType,
                uploadedBy, "Document Added");
    }

    /** Writes the bytes to disk, then the row and a history entry; the file is removed again if the row fails. */
    private void save(InsuranceClaim claim, byte[] bytes, String fileName, String extension, String contentType,
            String documentType, String uploadedBy, String historyAction) {
        String storagePath = files.write(claim.getRef(), extension, bytes);
        try {
            em.persist(new ClaimDocument(claim.getId(), documentType, fileName, contentType, bytes.length,
                    storagePath, uploadedBy));
            em.flush();
        } catch (RuntimeException e) {
            files.deleteQuietly(storagePath);
            throw e;
        }
        history.record(WorkflowHistory.CLAIM, claim.getRef(), claim.getCustomerName(), historyAction,
                claim.getStatus(), claim.getStatus(), documentType + ": " + fileName, uploadedBy);
    }

    private StoredFile open(InsuranceClaim claim, Long id) {
        ClaimDocument document = em.find(ClaimDocument.class, id);
        if (document == null || !document.getClaimId().equals(claim.getId())) {
            throw new NotFoundException("Document " + id + " not found on claim " + claim.getRef());
        }
        return new StoredFile(document.getFileName(), document.getContentType(), document.getSizeBytes(),
                files.read(document.getStoragePath(), "document " + id));
    }

    /** The real type from the file's first bytes; the browser's Content-Type and the extension are not trusted. */
    private static String detect(byte[] bytes) {
        if (startsWith(bytes, '%', 'P', 'D', 'F', '-')) {
            return "application/pdf";
        }
        if (startsWith(bytes, 0x89, 'P', 'N', 'G', 0x0D, 0x0A, 0x1A, 0x0A)) {
            return "image/png";
        }
        if (startsWith(bytes, 0xFF, 0xD8, 0xFF)) {
            return "image/jpeg";
        }
        return null;
    }

    private static boolean matches(String contentType, String extension) {
        return switch (contentType) {
            case "application/pdf" -> extension.equals("pdf");
            case "image/png" -> extension.equals("png");
            case "image/jpeg" -> extension.equals("jpg") || extension.equals("jpeg");
            default -> false;
        };
    }

    private static boolean startsWith(byte[] bytes, int... prefix) {
        if (bytes.length < prefix.length) {
            return false;
        }
        for (int i = 0; i < prefix.length; i++) {
            if ((bytes[i] & 0xFF) != prefix[i]) {
                return false;
            }
        }
        return true;
    }

    private static String cleanName(String original) {
        String name = original == null ? "" : original;
        name = name.substring(Math.max(name.lastIndexOf('/'), name.lastIndexOf('\\')) + 1);
        name = name.replaceAll("[\\p{Cntrl}\"]", "").trim();
        if (name.length() > 255) {
            name = name.substring(name.length() - 255);
        }
        return name.isEmpty() ? "document" : name;
    }

    private static String extension(String fileName) {
        int dot = fileName.lastIndexOf('.');
        return dot < 0 ? "" : fileName.substring(dot + 1).toLowerCase(Locale.ROOT);
    }
}
