package com.nsure.portfolio;

import com.nsure.common.exception.ConflictException;
import com.nsure.common.exception.NotFoundException;
import com.nsure.security.domain.AppUser;
import com.nsure.security.exception.NoAuthorizationException;
import com.nsure.security.service.PlatformSecurityContext;
import jakarta.persistence.EntityManager;
import jakarta.persistence.LockModeType;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.multipart.MultipartFile;

/**
 * Claim evidence files: PDF, JPG or PNG up to 10 MB, stored on local disk by {@link DocumentFiles}.
 * Staff need a claim permission; a customer may only touch claims on their own policies. Every upload enters the
 * {@link DocumentQuarantine} and becomes a claim document only once released (AT-SH09A-02).
 */
@Service
public class ClaimDocumentService {

    public static final long MAX_BYTES = 10L * 1024 * 1024;

    public static final List<String> TYPES = List.of(
            "Identity document", "Signed declaration", "Death certificate", "Medical report", "Hospital bill",
            "Supporting evidence");

    private static final String DEFAULT_TYPE = "Supporting evidence";
    /** Generated by the system, never uploaded, so neither is in TYPES. The final summary of a closed claim. */
    public static final String SUMMARY_TYPE = "Claim summary";
    /** A summary of an open claim so far; replaced by the next one, and by the final summary. */
    public static final String INTERIM_TYPE = "Interim claim summary";
    private static final DateTimeFormatter FILE_STAMP = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss");
    private static final Set<String> CLOSED = Set.of(ClaimWorkflow.PAID, ClaimWorkflow.REJECTED);

    /** Who may upload on the staff side: anyone who can lodge, update or assess a claim. */
    private static final List<String> STAFF_UPLOAD = List.of("UPDATE_CLAIM", "CREATE_CLAIM", "ASSESS_CLAIM");

    private final EntityManager em;
    private final ClaimWorkflow claims;
    private final WorkflowHistory history;
    private final PlatformSecurityContext security;
    private final PortfolioService portfolio;
    private final DocumentFiles files;
    private final DocumentCustody custody;
    private final DocumentQuarantine quarantine;
    /** NS-IL04-006: an adult insured life's medical evidence is shared with the policyholder only with consent. */
    private final LifeConsents consents;

    public ClaimDocumentService(EntityManager em, ClaimWorkflow claims, WorkflowHistory history,
            PlatformSecurityContext security, PortfolioService portfolio, DocumentFiles files,
            DocumentCustody custody, DocumentQuarantine quarantine, LifeConsents consents) {
        this.consents = consents;
        this.custody = custody;
        this.quarantine = quarantine;
        this.em = em;
        this.claims = claims;
        this.history = history;
        this.security = security;
        this.portfolio = portfolio;
        this.files = files;
    }

    /** A document's bytes plus what the download response needs to describe them. */
    public record StoredFile(String fileName, String contentType, long size, Resource resource) {
    }

    // ── staff ────────────────────────────────────────────────────────────────────────────────────────

    @Transactional(readOnly = true)
    public List<PortfolioViews.DocumentView> list(String ref) {
        security.authenticatedUser().validateHasPermissionTo("READ_CLAIM");
        return views(em, claims.claim(ref).getId());
    }

    @Transactional
    public List<PortfolioViews.DocumentView> upload(String ref, MultipartFile file, String type) {
        AppUser staff = security.authenticatedUser();
        if (STAFF_UPLOAD.stream().noneMatch(staff::hasPermissionTo)) {
            throw new NoAuthorizationException("User has no authority to add documents to a claim");
        }
        InsuranceClaim claim = claims.claim(ref);
        store(claim, file, type, staff.getUsername(), DocumentCustody.STAFF);
        return views(em, claim.getId());
    }

    @Transactional
    public StoredFile download(String ref, Long id) {
        AppUser staff = security.authenticatedUser();
        staff.validateHasPermissionTo("READ_CLAIM");
        return open(claims.claim(ref), id, staff.getUsername(), DocumentCustody.STAFF);
    }

    /** Who downloaded this claim's documents, and when (READ_AUDIT). */
    @Transactional(readOnly = true)
    public List<DocumentCustody.AccessView> accessLog(String ref) {
        security.authenticatedUser().validateHasPermissionTo("READ_AUDIT");
        return custody.accessLog(claims.claim(ref).getRef());
    }

    /**
     * Issues a claim summary. On an open claim it is an interim summary of the claim so far, and issuing again
     * replaces the earlier interim one. Once the claim is closed (Paid or Rejected) it is the final summary, the
     * record of the claim as decided: issued once, replacing any interim summary and any in an older layout. The row
     * lock means a double click, or two users at once, issue only one.
     */
    @Transactional
    public List<PortfolioViews.DocumentView> generateSummary(String ref) {
        AppUser staff = security.authenticatedUser();
        if (STAFF_UPLOAD.stream().noneMatch(staff::hasPermissionTo)) {
            throw new NoAuthorizationException("User has no authority to generate claim documents");
        }
        InsuranceClaim claim = claims.claim(ref);
        em.lock(claim, LockModeType.PESSIMISTIC_WRITE);
        if (!CLOSED.contains(claim.getStatus())) {
            replace(claim, summaries(claim.getId(), INTERIM_TYPE), staff.getUsername(), INTERIM_TYPE);
            return views(em, claim.getId());
        }
        if (summaries(claim.getId(), SUMMARY_TYPE).stream()
                .anyMatch(d -> d.getLayoutVersion() >= ClaimSummaryPdf.LAYOUT_VERSION)) {
            throw new ConflictException("Claim " + ref + " already has its claim summary. "
                    + "A summary is issued once per claim.");
        }
        replace(claim, summaries(claim.getId(), SUMMARY_TYPE, INTERIM_TYPE), staff.getUsername(), SUMMARY_TYPE);
        return views(em, claim.getId());
    }

    /** Ids of the closed claims holding a summary made in an older layout, for {@link DocumentLayoutUpgrade}. */
    @Transactional(readOnly = true)
    public List<Long> closedClaimsWithOldSummaries() {
        return em.createQuery("select distinct d.claimId from ClaimDocument d, InsuranceClaim c "
                        + "where c.id = d.claimId and c.status in :closed and d.documentType = :type "
                        + "and d.status = 'CURRENT' and d.layoutVersion < :layout order by d.claimId", Long.class)
                .setParameter("closed", CLOSED)
                .setParameter("type", SUMMARY_TYPE)
                .setParameter("layout", ClaimSummaryPdf.LAYOUT_VERSION)
                .getResultList();
    }

    /**
     * Replaces the old-layout summaries on a closed claim with one in the current layout, credited to whoever
     * issued the first. Does nothing if the claim has reopened or another instance got there first.
     */
    @Transactional
    public int replaceOldSummaries(Long claimId) {
        InsuranceClaim claim = em.find(InsuranceClaim.class, claimId, LockModeType.PESSIMISTIC_WRITE);
        if (claim == null || !CLOSED.contains(claim.getStatus())) {
            return 0;
        }
        List<ClaimDocument> summaries = summaries(claimId, SUMMARY_TYPE);
        if (summaries.isEmpty()
                || summaries.stream().anyMatch(d -> d.getLayoutVersion() >= ClaimSummaryPdf.LAYOUT_VERSION)) {
            return 0;
        }
        List<ClaimDocument> replaced = summaries(claimId, SUMMARY_TYPE, INTERIM_TYPE);
        replace(claim, replaced, summaries.get(0).getUploadedBy(), SUMMARY_TYPE);
        return replaced.size();
    }

    private List<ClaimDocument> summaries(Long claimId, String... types) {
        return em.createQuery("select d from ClaimDocument d where d.claimId = :claim and d.documentType in :types "
                        + "and d.status = 'CURRENT' order by d.id", ClaimDocument.class)
                .setParameter("claim", claimId)
                .setParameter("types", List.of(types))
                .getResultList();
    }

    /**
     * Files one new summary of the type and marks the given earlier summaries SUPERSEDED by it (Blueprint §8: issued
     * documents are kept, never overwritten or deleted).
     */
    private void replace(InsuranceClaim claim, List<ClaimDocument> old, String issuedBy, String type) {
        boolean interim = INTERIM_TYPE.equals(type);
        String reason = interim ? "Replaced by a newer interim summary"
                : old.stream().anyMatch(d -> INTERIM_TYPE.equals(d.getDocumentType()))
                        ? "Replaced by the final claim summary"
                        : "Reissued in the current summary layout (v" + ClaimSummaryPdf.LAYOUT_VERSION + ")";
        old.forEach(d -> d.supersede(null, reason));
        em.flush();
        List<PortfolioViews.DocumentView> evidence = views(em, claim.getId()).stream()
                .filter(d -> DocumentCustody.CURRENT.equals(d.status()))
                .toList();
        List<PortfolioViews.HistoryView> timeline = history.of(WorkflowHistory.CLAIM, claim.getRef()).stream()
                .filter(h -> !"Summary Generated".equals(h.action()) && !"Interim Summary Generated".equals(h.action()))
                .toList();
        InsurancePolicy policy = em.createQuery("select p from InsurancePolicy p where p.ref = :ref",
                        InsurancePolicy.class)
                .setParameter("ref", claim.getPolicyRef())
                .getResultStream()
                .findFirst()
                .orElse(null);
        byte[] pdf = ClaimSummaryPdf.render(claim, policy, ClaimWorkflow.results(claim), evidence, timeline, issuedBy);
        String fileName = claim.getRef() + (interim ? "-interim-summary-" : "-summary-")
                + LocalDateTime.now().format(FILE_STAMP) + ".pdf";
        ClaimDocument replacement = save(claim, pdf, fileName, "pdf", "application/pdf", type, issuedBy,
                interim ? "Interim Summary Generated" : "Summary Generated", ClaimSummaryPdf.LAYOUT_VERSION,
                old.isEmpty() ? null
                        : "replaces " + old.size() + (old.size() == 1 ? " earlier summary" : " earlier summaries")
                                + ", kept as superseded");
        old.forEach(d -> d.linkReplacement(replacement.getId()));
    }

    // ── customer portal ──────────────────────────────────────────────────────────────────────────────

    @Transactional
    public PortfolioViews.ShopView shopUpload(String ref, MultipartFile file, String type) {
        CustomerAccount account = portfolio.customerForLogin();
        store(ownClaim(account, ref), file, type, account.getLoginUsername(), DocumentCustody.PORTAL);
        return portfolio.shop();
    }

    @Transactional
    public StoredFile shopDownload(String ref, Long id) {
        CustomerAccount account = portfolio.customerForLogin();
        InsuranceClaim claim = ownClaim(account, ref);
        ClaimDocument document = em.find(ClaimDocument.class, id);
        if (document != null && claim.getId().equals(document.getClaimId())) {
            String withheld = consents.withheldFromPolicyholder(claim, document.getDocumentType(),
                    document.getUploadedBy(), account);
            if (withheld != null) {
                throw new com.nsure.security.exception.NoAuthorizationException(withheld);
            }
        }
        return open(claim, id, account.getLoginUsername(), DocumentCustody.PORTAL);
    }

    /**
     * The documents on one claim, oldest first, then the uploads still in quarantine or refused (listed so the
     * uploader sees their state, but with no id to download them by).
     */
    static List<PortfolioViews.DocumentView> views(EntityManager em, Long claimId) {
        List<PortfolioViews.DocumentView> views = new java.util.ArrayList<>(em.createQuery(
                        "select d from ClaimDocument d where d.claimId = :claim order by d.id", ClaimDocument.class)
                .setParameter("claim", claimId)
                .getResultStream()
                .map(d -> new PortfolioViews.DocumentView(
                        d.getId(), d.getDocumentType(), d.getFileName(), d.getContentType(), d.getSizeBytes(),
                        d.getUploadedBy(), d.getUploadedAt().withNano(0).toString(), d.getStatus(), d.getSha256(),
                        d.getSupersededBy(), d.getSupersededReason(), d.getScanStatus(),
                        DocumentIntake.sourceLabel(d.getSourceChannel()),
                        DocumentIntake.classification(d.getDocumentType()), intakeNote(d), null))
                .toList());
        views.addAll(DocumentQuarantine.heldViews(em, claimId));
        return views;
    }

    private static String intakeNote(ClaimDocument d) {
        return switch (d.getScanStatus()) {
            case DocumentIntake.RELEASED_UNSCANNED -> "Released from quarantine by " + d.getReleasedBy()
                    + " without a malware scan (no scanner is configured).";
            case DocumentIntake.CLEAN -> "Passed the malware scan (" + d.getReleasedBy() + ").";
            case DocumentIntake.NOT_SCANNED -> "Stored before uploads were quarantined; never scanned.";
            default -> null;
        };
    }

    private InsuranceClaim ownClaim(CustomerAccount account, String ref) {
        InsuranceClaim claim = claims.claim(ref);
        if (!account.getRef().equals(claim.getCustomerRef())) {
            // Not theirs: answer as if it did not exist rather than confirm someone else's claim number.
            throw new NotFoundException("Claim " + ref + " not found");
        }
        return claim;
    }

    /** Validates the upload and holds it in quarantine; it is not a claim document until released. */
    private void store(InsuranceClaim claim, MultipartFile file, String type, String uploadedBy, String channel) {
        if (CLOSED.contains(claim.getStatus())) {
            throw new IllegalArgumentException("Documents can only be added while the claim is open.");
        }
        String documentType = type == null || type.isBlank() ? DEFAULT_TYPE : type.trim();
        if (!TYPES.contains(documentType)) {
            throw new IllegalArgumentException("Document type must be one of: " + String.join(", ", TYPES) + ".");
        }
        if (file == null || file.isEmpty()) {
            throw new IllegalArgumentException("Choose a file to upload.");
        }
        if (file.getSize() > MAX_BYTES) {
            throw new IllegalArgumentException("Files can be at most 10 MB.");
        }
        byte[] bytes;
        try {
            bytes = file.getBytes();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        String fileName = cleanName(file.getOriginalFilename());
        String extension = extension(fileName);
        String contentType = detect(bytes);
        if (contentType == null || !matches(contentType, extension)) {
            throw new IllegalArgumentException("Only PDF, JPG and PNG files can be uploaded.");
        }
        quarantine.receive(claim, bytes, fileName, extension.equals("jpeg") ? "jpg" : extension, contentType,
                documentType, uploadedBy, channel);
    }

    /** Writes the bytes to disk, then the row and a history entry; the file is removed again if the row fails. */
    private ClaimDocument save(InsuranceClaim claim, byte[] bytes, String fileName, String extension, String contentType,
            String documentType, String uploadedBy, String historyAction, int layoutVersion, String note) {
        String storagePath = files.write(claim.getRef(), extension, bytes);
        ClaimDocument document = new ClaimDocument(claim.getId(), documentType, fileName, contentType, bytes.length,
                storagePath, uploadedBy, layoutVersion);
        document.seal(DocumentCustody.sha256(bytes));
        try {
            em.persist(document);
            em.flush();
        } catch (RuntimeException e) {
            files.deleteQuietly(storagePath);
            throw e;
        }
        DocumentText.index(em, DocumentText.CLAIM_TABLE, document.getId(), bytes, contentType);
        history.record(WorkflowHistory.CLAIM, claim.getRef(), claim.getCustomerName(), historyAction,
                claim.getStatus(), claim.getStatus(),
                documentType + ": " + fileName + (note == null ? "" : " · " + note), uploadedBy);
        return document;
    }

    private StoredFile open(InsuranceClaim claim, Long id, String username, String channel) {
        ClaimDocument document = em.find(ClaimDocument.class, id);
        if (document == null || !document.getClaimId().equals(claim.getId())) {
            throw new NotFoundException("Document " + id + " not found on claim " + claim.getRef());
        }
        custody.requireSensitiveAccess(document.getDocumentType(), security.authenticatedUser(), channel);
        custody.verify(document.getSha256(), document.getStoragePath(), "document " + id);
        custody.logAccess(DocumentCustody.CLAIM, id, claim.getRef(), document.getFileName(), username, channel);
        return new StoredFile(document.getFileName(), document.getContentType(), document.getSizeBytes(),
                files.read(document.getStoragePath(), "document " + id));
    }

    /** The real type from the file's first bytes; the browser's Content-Type and the extension are not trusted. */
    private static String detect(byte[] bytes) {
        if (startsWith(bytes, '%', 'P', 'D', 'F', '-')) {
            return "application/pdf";
        }
        if (startsWith(bytes, 0x89, 'P', 'N', 'G', 0x0D, 0x0A, 0x1A, 0x0A)) {
            return "image/png";
        }
        if (startsWith(bytes, 0xFF, 0xD8, 0xFF)) {
            return "image/jpeg";
        }
        return null;
    }

    private static boolean matches(String contentType, String extension) {
        return switch (contentType) {
            case "application/pdf" -> extension.equals("pdf");
            case "image/png" -> extension.equals("png");
            case "image/jpeg" -> extension.equals("jpg") || extension.equals("jpeg");
            default -> false;
        };
    }

    private static boolean startsWith(byte[] bytes, int... prefix) {
        if (bytes.length < prefix.length) {
            return false;
        }
        for (int i = 0; i < prefix.length; i++) {
            if ((bytes[i] & 0xFF) != prefix[i]) {
                return false;
            }
        }
        return true;
    }

    private static String cleanName(String original) {
        String name = original == null ? "" : original;
        name = name.substring(Math.max(name.lastIndexOf('/'), name.lastIndexOf('\\')) + 1);
        name = name.replaceAll("[\\p{Cntrl}\"]", "").trim();
        if (name.length() > 255) {
            name = name.substring(name.length() - 255);
        }
        return name.isEmpty() ? "document" : name;
    }

    private static String extension(String fileName) {
        int dot = fileName.lastIndexOf('.');
        return dot < 0 ? "" : fileName.substring(dot + 1).toLowerCase(Locale.ROOT);
    }
}
